import { db, FieldValue } from "../lib/firestore.js";
import { toProjectId } from "../utils/project.js";
import type { GeneratedArtifact } from "../types.js";
import { dropJobCache } from "./jobProgressCache.js";

interface SaveTestInput {
  /** Firebase uid of the owner; Firestore Rules only let this user read the test case. */
  ownerUid: string;
  projectName: string;
  url: string;
  script: string;
  title?: string;
  type?: "UI" | "API";
  criteria?: string[];
  generationJobId?: string;
  generationCaseId?: string;
  pageId?: string;
  /** The script uses computed assertions the MCP engine cannot replay (GENERATION_MODE=ecommerce). */
  requiresPlaywrightEngine?: boolean;
}

export interface ExecutionTestCase {
  id: string;
  projectId: string;
  projectName: string;
  script: string;
  ownerUid?: string;
  generationJobId?: string;
  requiresPlaywrightEngine?: boolean;
}

export const saveGeneratedTestCase = async (input: SaveTestInput): Promise<string> => {
  const projectId = toProjectId(input.projectName || input.url);
  const docRef = await db.collection("testCases").add({
    ownerUid: input.ownerUid,
    projectId,
    projectName: input.projectName || input.url,
    title: input.title || `Generated test - ${new Date().toISOString()}`,
    type: input.type || "UI",
    script: input.script,
    criteria: input.criteria || [],
    sourceUrl: input.url,
    ...(input.generationJobId ? { generationJobId: input.generationJobId } : {}),
    ...(input.generationCaseId ? { generationCaseId: input.generationCaseId } : {}),
    ...(input.pageId ? { pageId: input.pageId } : {}),
    ...(input.requiresPlaywrightEngine ? { requiresPlaywrightEngine: true } : {}),
    lastStatus: "pending",
    lastRunAt: null,
    createdAt: FieldValue.serverTimestamp(),
    updatedAt: FieldValue.serverTimestamp(),
  });

  return docRef.id;
};

export const getTestCasesByIds = async (ids: string[]) => {
  const snapshots = await Promise.all(ids.map((id) => db.collection("testCases").doc(id).get()));
  return snapshots
    .filter((s) => s.exists)
    .map((s) => {
      const data = s.data() as Record<string, unknown>;
      return {
        id: s.id,
        projectId: String(data.projectId ?? ""),
        projectName: String(data.projectName ?? ""),
        script: String(data.script ?? ""),
        ...(typeof data.ownerUid === "string" && data.ownerUid ? { ownerUid: data.ownerUid } : {}),
        ...(typeof data.generationJobId === "string" && data.generationJobId
          ? { generationJobId: data.generationJobId }
          : {}),
        ...(data.requiresPlaywrightEngine === true ? { requiresPlaywrightEngine: true } : {}),
      } satisfies ExecutionTestCase;
    });
};

export const updateTestCaseStatus = async (
  testCaseId: string,
  status: "pass" | "fail" | "flaky" | "running" | "pending",
): Promise<void> => {
  await db.collection("testCases").doc(testCaseId).update({
    lastStatus: status,
    lastRunAt: FieldValue.serverTimestamp(),
    updatedAt: FieldValue.serverTimestamp(),
  });
};

export const updateTestCaseScript = async (testCaseId: string, script: string): Promise<void> => {
  await db.collection("testCases").doc(testCaseId).update({
    script,
    updatedAt: FieldValue.serverTimestamp(),
  });
};

export class TestCaseAccessError extends Error {
  constructor(message = "Test case not found") {
    super(message);
    this.name = "TestCaseAccessError";
  }
}

/**
 * Throws TestCaseAccessError unless every listed test case exists and belongs to ownerUid.
 * Missing and foreign cases get the same error, so other users' ids can't be probed.
 */
export const assertOwnsTestCases = async (ids: string[], ownerUid: string): Promise<void> => {
  const snapshots = await Promise.all([...new Set(ids)].map((id) => db.collection("testCases").doc(id).get()));
  if (snapshots.some((snapshot) => !snapshot.exists || snapshot.get("ownerUid") !== ownerUid)) {
    throw new TestCaseAccessError();
  }
};

export class TestCaseDeleteError extends Error {
  constructor(message: string, public readonly statusCode: 404 | 409) {
    super(message);
    this.name = "TestCaseDeleteError";
  }
}

/** Firestore's array-contains-any accepts at most 30 values. */
const chunk = <T>(items: T[], size: number): T[][] =>
  Array.from({ length: Math.ceil(items.length / size) }, (_, index) => items.slice(index * size, (index + 1) * size));

/**
 * Deletes test cases. A case generated by a job also has its job case reset to "planned"
 * (and the job's completed count lowered), so the job can generate a fresh script for it.
 * Refuses while a run that includes one of the cases is still in progress.
 */
export const deleteTestCases = async (ids: string[], ownerUid: string): Promise<{ deletedIds: string[] }> => {
  const uniqueIds = [...new Set(ids)];
  const snapshots = (await Promise.all(uniqueIds.map((id) => db.collection("testCases").doc(id).get())))
    .filter((snapshot) => snapshot.exists);
  if (!snapshots.length) return { deletedIds: [] };
  if (snapshots.some((snapshot) => snapshot.get("ownerUid") !== ownerUid)) {
    throw new TestCaseDeleteError("Test case not found", 404);
  }

  const existingIds = snapshots.map((snapshot) => snapshot.id);
  for (const idChunk of chunk(existingIds, 30)) {
    const running = await db.collection("testRuns")
      .where("status", "==", "running")
      .where("testCaseIds", "array-contains-any", idChunk)
      .limit(1)
      .get();
    if (!running.empty) {
      throw new TestCaseDeleteError("A test run that includes one of these test cases is still running. Wait for it to finish.", 409);
    }
  }

  const jobIds = [...new Set(snapshots
    .map((snapshot) => snapshot.get("generationJobId"))
    .filter((jobId): jobId is string => typeof jobId === "string" && jobId.length > 0))];
  const jobSnapshots = await Promise.all(jobIds.map((jobId) => db.collection("generationJobs").doc(jobId).get()));
  // Only reset plan cases in jobs this user owns.
  const existingJobIds = new Set(jobSnapshots
    .filter((snapshot) => snapshot.exists && snapshot.get("ownerUid") === ownerUid)
    .map((snapshot) => snapshot.id));

  const batch = db.batch();
  const resetCountByJob = new Map<string, number>();
  for (const snapshot of snapshots) {
    batch.delete(snapshot.ref);

    const jobId = snapshot.get("generationJobId");
    const caseId = snapshot.get("generationCaseId");
    if (typeof jobId !== "string" || typeof caseId !== "string" || !existingJobIds.has(jobId)) continue;
    const caseRef = db.collection("generationJobs").doc(jobId).collection("cases").doc(caseId);
    const caseSnapshot = await caseRef.get();
    if (!caseSnapshot.exists || caseSnapshot.get("testCaseId") !== snapshot.id) continue;

    batch.update(caseRef, {
      status: "planned",
      testCaseId: FieldValue.delete(),
      retryStatus: "idle",
      retryTestCaseId: FieldValue.delete(),
      errorMessage: FieldValue.delete(),
    });
    resetCountByJob.set(jobId, (resetCountByJob.get(jobId) ?? 0) + 1);
  }
  for (const [jobId, count] of resetCountByJob) {
    batch.update(db.collection("generationJobs").doc(jobId), { completedCaseCount: FieldValue.increment(-count) });
  }

  await batch.commit();
  for (const jobId of resetCountByJob.keys()) dropJobCache(jobId);
  return { deletedIds: existingIds };
};

export const artifactToSavePayload = (
  artifact: GeneratedArtifact,
  projectName: string,
  url: string,
  ownerUid: string,
): SaveTestInput => ({
  ownerUid,
  projectName,
  url,
  title: artifact.title,
  type: artifact.type,
  criteria: artifact.criteria,
  script: artifact.script,
});
